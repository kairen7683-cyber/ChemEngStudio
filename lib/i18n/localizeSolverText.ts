export function localizeMetricKey(key: string, isEn: boolean): string {
  if (!isEn) return key;
  return METRIC_KEY_EN[key] ?? localizeSolverText(key, true);
}

export function localizeSolverText(text: string | undefined | null, isEn: boolean): string {
  if (!text) return '';
  if (!isEn) return text;
  let out = text;
  for (const [pattern, replacement] of TEXT_REPLACEMENTS_EN) {
    out = out.replace(pattern, replacement);
  }
  return out;
}
