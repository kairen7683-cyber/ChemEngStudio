#!/usr/bin/env node
import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

const ENTRY = path.join(ROOT, 'lib', 'calculations', 'chemproUnifiedKernel.ts');
const OUTFILE = path.join(ROOT, 'public', 'chempro', 'unified_kernel.js');

async function main() {
  if (!fs.existsSync(ENTRY)) {
    throw new Error(`Missing unified kernel entrypoint: ${ENTRY}`);
  }

  await build({
    entryPoints: [ENTRY],
    outfile: OUTFILE,
    bundle: true,
    format: 'iife',
    globalName: '__ChemEngUnifiedKernelBundle',
    platform: 'browser',
    target: ['es2020'],
    minify: true,
    sourcemap: false,
    tsconfig: path.join(ROOT, 'tsconfig.json'),
    absWorkingDir: ROOT,
    logLevel: 'info',
    banner: {
      js: '/* AUTO-GENERATED by scripts/buildUnifiedChemproKernel.mjs — Do not edit directly. Source: lib/calculations/chemproUnifiedKernel.ts */',
    },
  });

  const stat = fs.statSync(OUTFILE);
  const sizeKb = (stat.size / 1024).toFixed(1);
  console.log(`[buildUnifiedChemproKernel] Built ${OUTFILE} (${sizeKb} KB)`);
}

main().catch((err) => {
  console.error('[buildUnifiedChemproKernel] FAILED:', err);
  process.exit(1);
});
